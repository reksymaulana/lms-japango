def get_language(request: Request) -> str:
    language = request.cookies.get("lang", "id")
    return language if language in TRANSLATIONS else "id"


def template_context(request: Request) -> dict[str, Any]:
    language = get_language(request)
    return {
        "lang": language,
        "t": TRANSLATIONS[language],
        "grammar_english": GRAMMAR_ENGLISH,
        "current_user": getattr(request.state, "account", None),
    }


def create_templates(directory: str | Path) -> Jinja2Templates:
    return Jinja2Templates(
        directory=str(directory),
        context_processors=[template_context],
    )
